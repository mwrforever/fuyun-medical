package com.fuyun.patient.api;

/**
 * 「在途就诊查询」SPI 扩展点（M02 红线 4 依赖倒置：本模块定义契约，业务模块注册实现——
 * M03 门诊未结就诊 / M04 在院状态；本模块不反向依赖业务模块的编译期实现）。
 *
 * <p><b>冻结语义（2026-09-16 拍板，随 PR-2 计划审批确认）</b>：Spring 容器内无任何本接口实现
 * （M03/M04 未上线阶段）时，合并前置检查视为「无在途就诊」放行并记录 warn 日志——不阻断合并演示
 * 与集成测试；任一实现注册后自动收紧为「命中即阻断」（对齐协和「未完成就诊禁止合并」实践）。
 * 该语义为本契约不可分割的一部分，修改须经消费方（M03/M04）双向评审。
 */
public interface OngoingVisitQuery {

    /**
     * 判定患者是否存在在途就诊（合并前置检查依据）。
     *
     * @param patientId 患者主索引（合并前会对主档与从档各查一次）；来源：M02 合并流程
     * @return true=存在在途就诊（阻断合并）；false=无在途就诊（放行）
     */
    boolean hasOngoingVisit(long patientId);
}
